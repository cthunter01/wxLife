template <std::size_t N>
std::string bytes(const std::array<unsigned char, N>& data)
{
    return {data.begin(), data.end()};
}

// The texts behind the vectors, built again here.
constexpr std::string_view kHello = "hello, hello, hello!";

std::string table()
{
    std::string text;
    for (int i = 0; i < 300; ++i)
    {
        text += std::format("{:03d} o{}o$\n", i, std::string(static_cast<std::size_t>(i % 7), 'b'));
    }
    return text;
}

constexpr std::size_t kPlenty = 1 << 20;

TEST(GzipTest, Crc32MatchesTheStandardCheckValue)
{
    EXPECT_EQ(crc32("123456789"), 0xcbf43926U);
    EXPECT_EQ(crc32(""), 0U);
    EXPECT_EQ(crc32("6789", crc32("12345")), 0xcbf43926U);  // it continues
}

TEST(GzipTest, RecognisesTheMagicBytes)
{
    EXPECT_TRUE(isGzip(bytes(kEmpty)));
    EXPECT_FALSE(isGzip("x = 3, y = 3"));
    EXPECT_FALSE(isGzip("\x1f"));
    EXPECT_FALSE(isGzip(""));
}

TEST(GzipTest, UnpacksEveryKindOfBlock)
{
    EXPECT_EQ(gunzip(bytes(kEmpty), kPlenty), "");
    EXPECT_EQ(gunzip(bytes(kHelloFixed), kPlenty), kHello);
    EXPECT_EQ(gunzip(bytes(kHelloStored), kPlenty), kHello);
    EXPECT_EQ(gunzip(bytes(kTableDynamic), kPlenty), table());
    // Copies that overlap what they write: distance 1, 258 bytes at a time.
    EXPECT_EQ(gunzip(bytes(kRunOfA), kPlenty), std::string(10000, 'a'));
}

TEST(GzipTest, SkipsEveryOptionalHeaderField)
{
    EXPECT_EQ(gunzip(bytes(kAllHeaderFields), kPlenty), kHello);
}

TEST(GzipTest, JoinsMembersAndIgnoresZeroPadding)
{
    EXPECT_EQ(gunzip(bytes(kTwoMembers), kPlenty), "abcdef");
}

TEST(GzipTest, RefusesWhatItCannotTrust)
{
    const auto error = [](const std::string& data, std::size_t maxSize = kPlenty) {
        const auto result = gunzip(data, maxSize);
        return result ? std::string("no error") : result.error();
    };
    EXPECT_EQ(error("x = 3, y = 3, rule = B3/S23"), "The data is not gzip.");
    EXPECT_EQ(error(""), "The data ends too early.");

    const std::string table = bytes(kTableDynamic);
    EXPECT_EQ(error(table.substr(0, table.size() - 10)), "The data ends too early.");
    EXPECT_EQ(error(table.substr(0, 12)), "The data ends too early.");
    std::string badCrc = table;
    badCrc[badCrc.size() - 8] ^= 1;
    EXPECT_EQ(error(badCrc), "The data is damaged: its checksum does not match.");
    std::string badLength = table;
    badLength[badLength.size() - 4] ^= 1;
    EXPECT_EQ(error(badLength), "The data is damaged: its length does not match.");
    std::string badMethod = table;
    badMethod[2]          = 7;
    EXPECT_EQ(error(badMethod), "The data uses an unknown compression method.");
    std::string badFlags = table;
    badFlags[3]          = static_cast<char>(0x80);
    EXPECT_EQ(error(badFlags), "The gzip header sets flags that do not exist.");

    EXPECT_EQ(error(bytes(kDistanceTooFar)), "The data refers to bytes before its start.");
    EXPECT_EQ(error(bytes(kBlockTypeThree)), "The data holds a block of an unknown kind.");
    EXPECT_EQ(error(bytes(kRunOfA), 9999), "The data unpacks to more than 9999 bytes.");
    EXPECT_EQ(error(bytes(kRunOfA), 10000), "no error");
    EXPECT_EQ(error(bytes(kHelloStored), 19), "The data unpacks to more than 19 bytes.");
    // Garbage after a member, other than zeros, is not a member.
    EXPECT_EQ(error(bytes(kHelloFixed) + "junk"), "The data is not gzip.");
}

